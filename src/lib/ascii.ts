export const STYLES: { id: string; label: string; filled: string; empty: string }[] = [
  { id: "solid", label: "Solid block", filled: "█", empty: "░" },
  { id: "shade", label: "Shade", filled: "▓", empty: "░" },
  { id: "heavy", label: "Heavy", filled: "▰", empty: "▱" },
  { id: "hash", label: "ASCII", filled: "#", empty: "." },
  { id: "dots", label: "Dots", filled: "●", empty: "·" },
  { id: "braille", label: "Braille", filled: "⣿", empty: "⠀" },
  { id: "stars", label: "Stars", filled: "★", empty: "☆" },
];

export function textToRows(text: string): string[][] {
  const glyphs = Array.from(text.toUpperCase())
    .map((character) => FONT[character] ?? FONT[character === " " ? " " : "?"] ?? FONT["?"])
    .filter(Boolean);
  const rows: string[][] = Array.from({ length: 7 }, () => []);
  for (const glyph of glyphs) {
    for (let row = 0; row < 7; row += 1) {
      rows[row].push(glyph[row]);
    }
  }
  return rows.map((row) => row.join(" ").split(""));
}

export function rowsToGrid(rows: string[][], filled = "█", empty = " "): string {
  return rows
    .map((row) => row.map((cell) => (cell === "1" || cell === "#" ? filled : empty)).join(""))
    .join("\n");
}

export function textToArt(text: string, styleId = "solid"): string {
  const style = STYLES.find((item) => item.id === styleId) ?? STYLES[0];
  return rowsToGrid(textToRows(text), style.filled, " ");
}

export function decodeGalleryArt(raw: string): string[][] {
  const rows = 13;
  const width = Math.max(1, Math.floor(raw.length / rows));
  const out: string[][] = [];
  for (let index = 0; index < rows; index += 1) {
    const row = raw.slice(index * width, (index + 1) * width);
    out.push(Array.from(row));
  }
  return out;
}

export function encodeForChat(rows: string[][], background = "░"): string {
  return rows
    .map((row) =>
      row
        .map((cell) => (cell === " " || cell === "\n" ? background : cell))
        .join(""),
    )
    .join("");
}

export function artToChat(raw: string): string {
  return encodeForChat(decodeGalleryArt(raw));
}

export function normalizeDrawRow(row: string[]) {
  return row.map((cell) => (cell ? cell : " "));
}
